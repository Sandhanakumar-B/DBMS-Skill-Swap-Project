package com.skillswap.dao;

import com.skillswap.config.DatabaseConnection;
import com.skillswap.model.Student;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Data Access Object (DAO) for the STUDENTS table.
 * Encapsulates all SQL queries using PreparedStatements and try-with-resources.
 */
public class StudentDAO {

    /**
     * Inserts a new student record into the database and populates its generated student_id.
     * 
     * @param student The student object to insert
     * @return The student with its generated student_id and created_at populated
     * @throws SQLException if a database error occurs (e.g. duplicate email)
     */
    public Student insertStudent(Student student) throws SQLException {
        String sql = "INSERT INTO STUDENTS (student_name, email, contact_info) VALUES (?, ?, ?)";

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            stmt.setString(1, student.getStudentName());
            stmt.setString(2, student.getEmail());
            stmt.setString(3, student.getContactInfo());

            int affectedRows = stmt.executeUpdate();
            if (affectedRows == 0) {
                throw new SQLException("Creating student failed, no rows affected.");
            }

            try (ResultSet generatedKeys = stmt.getGeneratedKeys()) {
                if (generatedKeys.next()) {
                    int generatedId = generatedKeys.getInt(1);
                    student.setStudentId(generatedId);
                } else {
                    throw new SQLException("Creating student failed, no ID obtained.");
                }
            }

            // Retrieve the created_at timestamp generated by MySQL
            return findStudentById(student.getStudentId())
                    .orElse(student);
        }
    }

    /**
     * Finds a student by their unique primary key ID.
     */
    public Optional<Student> findStudentById(int studentId) throws SQLException {
        String sql = "SELECT student_id, student_name, email, contact_info, created_at FROM STUDENTS WHERE student_id = ?";

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setInt(1, studentId);

            try (ResultSet rs = stmt.executeQuery()) {
                if (rs.next()) {
                    return Optional.of(mapResultSetToStudent(rs));
                }
            }
        }
        return Optional.empty();
    }

    /**
     * Finds a student by their unique email address.
     */
    public Optional<Student> findStudentByEmail(String email) throws SQLException {
        String sql = "SELECT student_id, student_name, email, contact_info, created_at FROM STUDENTS WHERE LOWER(email) = LOWER(?)";

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setString(1, email.trim());

            try (ResultSet rs = stmt.executeQuery()) {
                if (rs.next()) {
                    return Optional.of(mapResultSetToStudent(rs));
                }
            }
        }
        return Optional.empty();
    }

    /**
     * Retrieves all registered students ordered by student_id.
     */
    public List<Student> findAllStudents() throws SQLException {
        String sql = "SELECT student_id, student_name, email, contact_info, created_at FROM STUDENTS ORDER BY student_id ASC";
        List<Student> students = new ArrayList<>();

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql);
             ResultSet rs = stmt.executeQuery()) {

            while (rs.next()) {
                students.add(mapResultSetToStudent(rs));
            }
        }
        return students;
    }

    /**
     * Checks if a given email is already registered in the database.
     */
    public boolean emailExists(String email) throws SQLException {
        String sql = "SELECT 1 FROM STUDENTS WHERE LOWER(email) = LOWER(?) LIMIT 1";

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setString(1, email.trim());

            try (ResultSet rs = stmt.executeQuery()) {
                return rs.next();
            }
        }
    }

    /**
     * Returns total count of registered students.
     */
    public int getTotalStudentsCount() throws SQLException {
        String sql = "SELECT COUNT(*) FROM STUDENTS";

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql);
             ResultSet rs = stmt.executeQuery()) {

            if (rs.next()) {
                return rs.getInt(1);
            }
        }
        return 0;
    }

    /**
     * Deletes a student by ID (for cleanup and testing purposes).
     */
    public boolean deleteStudent(int studentId) throws SQLException {
        String sql = "DELETE FROM STUDENTS WHERE student_id = ?";

        try (Connection conn = DatabaseConnection.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setInt(1, studentId);
            return stmt.executeUpdate() > 0;
        }
    }

    /**
     * Helper to map a SQL ResultSet row to a Student model object.
     */
    private Student mapResultSetToStudent(ResultSet rs) throws SQLException {
        return new Student(
                rs.getInt("student_id"),
                rs.getString("student_name"),
                rs.getString("email"),
                rs.getString("contact_info"),
                rs.getTimestamp("created_at")
        );
    }
}
